function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en" className="dark" suppressHydrationWarning>
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    // Apply saved theme
    const t = localStorage.getItem("cg-theme");
    document.documentElement.classList.toggle("dark", t !== "light");

    // Re-validate routes + data when Firebase auth state changes
    const unsub = onFirebaseAuthChange(async (user) => {
      if (user) {
        // Ensure Supabase session is live so RLS works
        const { data: existing } = await supabase.auth.getSession();
        if (!existing?.session) {
          // Google user: try id_token exchange; email user: try password bridge
          // For page-refresh cases where we don't have the raw credentials,
          // try to refresh the existing Supabase token first
          await supabase.auth.refreshSession().catch(() => {});
        }
      }
      router.invalidate();
      queryClient.invalidateQueries();
    });
    return unsub;
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <Outlet />
      <Toaster richColors position="top-right" />
    </QueryClientProvider>
  );
}
